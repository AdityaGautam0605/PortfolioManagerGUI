-- Hosted tables are separate from the original local stocks/portfolio tables.
CREATE TABLE IF NOT EXISTS folio_accounts (
  id VARCHAR(36) PRIMARY KEY,
  username VARCHAR(40) NOT NULL UNIQUE,
  password_hash VARCHAR(100) NOT NULL,
  salt VARCHAR(40) NOT NULL
);
CREATE TABLE IF NOT EXISTS folio_sessions (
  token_hash VARCHAR(64) PRIMARY KEY,
  owner_id VARCHAR(36) NOT NULL,
  expires_at TIMESTAMP NOT NULL,
  FOREIGN KEY (owner_id) REFERENCES folio_accounts(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS folio_stocks (
  owner_id VARCHAR(36) NOT NULL,
  symbol VARCHAR(20) NOT NULL,
  name VARCHAR(255) NOT NULL,
  price DECIMAL(20,6) NOT NULL,
  PRIMARY KEY (owner_id, symbol),
  FOREIGN KEY (owner_id) REFERENCES folio_accounts(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS folio_entries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id VARCHAR(36) NOT NULL,
  symbol VARCHAR(20) NOT NULL,
  quantity INT NOT NULL,
  buy_price DECIMAL(20,6) NOT NULL,
  FOREIGN KEY (owner_id, symbol) REFERENCES folio_stocks(owner_id, symbol) ON DELETE CASCADE
);
